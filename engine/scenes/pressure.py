"""Сцены «давление в пласте»: упругий режим, кадры класса B, расчёт по формулам главы.

Модель одна: уравнение пьезопроводности. Параметры условные (κ = 1 м²/с), метка «симуляция».
check() сверяет модель с погрешностями, которые автор приводит в книге.

Запуск: python engine/scenes/pressure.py --dir data/basniev   -> SVG и data/basniev/extra_illustrations.json
"""
