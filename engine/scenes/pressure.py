def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    d = pathlib.Path(ap.parse_args().dir)
    layer = json.loads((d / "layer.json").read_text(encoding="utf-8-sig"))
    nodes = {n["id"]: n for n in layer["nodes"]}
    (d / "illustrations").mkdir(exist_ok=True)
    extra = {}
    for slug, (svg, caption, alt) in scenes().items():
        nid = f"{layer['chapter']}.{slug}"
        if nid not in nodes:
            print("нет узла", nid)
            continue
        name = f"illustrations/{nid}.model.svg"
        (d / name).write_text(svg, encoding="utf-8")
        extra[nid] = [{"id": f"{nid}.m1", "file": name, "frame_class": "B", "origin": "code_from_model", "label": "симуляция",
                       "caption": caption, "alt": alt, "source": None, "claim_ids": [c["id"] for c in nodes[nid]["claims"]][:3],
                       "prompt": None}]
    (d / "extra_illustrations.json").write_text(json.dumps(extra, ensure_ascii=False, indent=1), encoding="utf-8")
    for what, book, model in check():
        print(f"{'OK ' if abs(book - model) <= max(0.06 * book, 0.06) else 'РАСХОЖДЕНИЕ '} {what}: книга {book}, модель {model:.2f}")
    print(f"расчётных сцен {len(extra)}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
