K = 1.0  # пьезопроводность, м²/с: внутри диапазона главы 0,1–5
EULER = 0.5772156649


def e1(x):
    """Интегральная показательная функция −Ei(−x)."""
    if x <= 1:
        s, term = -EULER - math.log(x), 1.0
        for n in range(1, 60):
            term *= -x / n
            s -= term / n
        return s
    b, c = x + 1, 1e300
    d = 1 / b
    h = d
    for i in range(1, 200):
        a = -i * i
        b += 2
        d = 1 / (a * d + b)
        c = b + a / c
        h *= c * d
        if abs(c * d - 1) < 1e-12:
            break
    return h * math.exp(-x)


def check():
    """(что, в книге, по модели): совпадение значит, что картинка и книга об одном."""
    half = lambda f: 0.5 * math.log(1 + 4 * f) / (0.5 * e1(1 / (4 * f))) - 1
    return [("ПССС, постоянный дебит галереи, депрессия, %", 25, 100 * (math.sqrt(2) / (2 / math.sqrt(math.pi)) - 1)),
            ("ПССС, постоянное давление, дебит, %", 11, 100 * (1 - 0.5 * math.sqrt(math.pi))),
            ("ПССС, скважина, f0=100, депрессия, %", 10.6, 100 * half(100)),
            ("ПССС, скважина, f0=1000, депрессия, %", 7.5, 100 * half(1000)),
            ("ПССС, скважина, f0=10000, депрессия, %", 5.7, 100 * half(10000)),
            ("логарифм вместо Ei при x=0,01, %", 0.25, 100 * abs(e1(0.01) / (-EULER - math.log(0.01)) - 1)),
            ("логарифм вместо Ei при x=0,1, %", 5.7, 100 * abs(e1(0.1) / (-EULER - math.log(0.1)) - 1)),
            ("логарифм вместо Ei при x=0,14, %", 9.7, 100 * abs(e1(0.14) / (-EULER - math.log(0.14)) - 1))]


def span(a, b, n=80):
    return [a + (b - a) * i / (n - 1) for i in range(n)]


def logspan(a, b, n=80):
    return [10 ** v for v in span(math.log10(a), math.log10(b), n)]


def tone(i, n):
    return mix("#1F9094", "#A8F7F4", i / (n - 1))


